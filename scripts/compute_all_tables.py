def norm(arr):
    mn = np.min(arr)
    mx = np.max(arr)
    if mx > mn:
        return (np.array(arr, dtype=float) - mn) / (mx - mn)
    return np.zeros_like(arr, dtype=float)

# Compute Composite Scores
composite = {}
best_algo = {}

for regimen in ['Intra-Domain', 'Cross-Domain']:
    composite[regimen] = {}
    best_algo[regimen] = {}
    for freq in frequencies:
        composite[regimen][freq] = {}
        best_algo[regimen][freq] = {}
        for app in appliances:
            entry = data[regimen][freq][app]
            mae = np.array(entry['MAE'], dtype=float)
            f1 = np.array(entry['F1'], dtype=float)
            nep = np.array(entry['NEP'], dtype=float)
            
            comp = norm(mae) + (1.0 - f1) + norm(nep)
            comp_rounded = np.round(comp, 2)
            composite[regimen][freq][app] = comp_rounded
            
            best_idx = np.argmin(comp_rounded)
            best_algo[regimen][freq][app] = models[best_idx]

print("=== TABLE 3: COMPOSITE SCORES ===")
for freq in frequencies:
    for app in appliances:
        intra_scores = composite['Intra-Domain'][freq][app]
        cross_scores = composite['Cross-Domain'][freq][app]
        
        # Format strings with bold for minimum
        intra_min_idx = np.argmin(intra_scores)
        cross_min_idx = np.argmin(cross_scores)
        
        intra_str = " / ".join([f"**{val:.2f}**" if i == intra_min_idx else f"{val:.2f}" for i, val in enumerate(intra_scores)])
        cross_str = " / ".join([f"**{val:.2f}**" if i == cross_min_idx else f"{val:.2f}" for i, val in enumerate(cross_scores)])
        
        print(f"| {freq} | {app} | {intra_str} | {cross_str} |")

print("\n=== TABLE 4: BEST PERFORMING ALGORITHMS ===")
for regimen in ['Intra-Domain', 'Cross-Domain']:
    for freq in frequencies:
        row = [best_algo[regimen][freq][app] for app in appliances]
        print(f"| {regimen} | {freq} | " + " | ".join(row) + " |")
